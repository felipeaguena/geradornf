def parse_feiras():
    lines = [l for l in CSV_DATA.strip().splitlines()]
    reader = csv.reader(lines)
    all_rows = list(reader)
    # Linha 0: Descrição das Feiras,DESCRIÇÃO DA FEIRA,,,,
    # Linha 1: ,Feira,Data da Feira,"Deadline\n-30 dias da feira",Local,Organizador
    # Linhas 2 em diante: itens
    itens = []
    for r in all_rows[2:]:
        if not r or len(r) < 2:
            continue
        nome = r[1].strip() if len(r) > 1 else ""
        data_feira = r[2].strip() if len(r) > 2 else ""
        deadline = r[3].strip() if len(r) > 3 else ""
        local = r[4].strip() if len(r) > 4 else ""
        organizador = r[5].strip() if len(r) > 5 else ""
        if nome:
            itens.append({
                "nome": nome,
                "data_feira": data_feira,
                "deadline": deadline,
                "local": local,
                "organizador": organizador
            })
    return itens

